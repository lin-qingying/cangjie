package org.cangnova.cangjie.psi.test

import java.io.File

/**
 * PSI 模块 testData 驱动测试的生成器。
 *
 * 扫描 `psi/testData/lexer` 与 `psi/testData/parsing` 下的 `.cj` 文件，
 * 在 `psi/tests-gen/org/cangnova/cangjie/psi/test` 生成 JUnit5 测试套件
 * （@Nested 嵌套类对应目录结构），分别挂到 AbstractCjLexerTest /
 * AbstractCjParsingTest 基类上。由 project-tests-convention 的
 * `testGenerator(...)` 在 compileTestKotlin 前自动执行。
 *
 * 用法（仓库根目录）：
 * ```
 * ./gradlew :psi:generateTestGeneratorForPsiTests
 * ```
 */
object TestGeneratorForPsi {

    @JvmStatic
    fun main(args: Array<String>) {
        val projectRoot = if (args.isNotEmpty()) File(args[0]) else File(System.getProperty("user.dir"))
        cleanGeneratedTests(projectRoot)

        generateSuite(
            projectRoot = projectRoot,
            relativeTestDataRoot = "psi/testData/lexer",
            generatedClassName = "CjLexerTestGenerated",
            baseClassName = "AbstractCjLexerTest",
        )

        generateSuite(
            projectRoot = projectRoot,
            relativeTestDataRoot = "psi/testData/parsing",
            generatedClassName = "CjParsingTestGenerated",
            baseClassName = "AbstractCjParsingTest",
        )

        generateSuite(
            projectRoot = projectRoot,
            relativeTestDataRoot = "psi/testData/cjd",
            generatedClassName = "CjdParsingTestGenerated",
            baseClassName = "AbstractCjDeclarationParsingTest",
        )

        generateSuite(
            projectRoot = projectRoot,
            relativeTestDataRoot = "psi/testData/cdoc",
            generatedClassName = "CdocLexerTestGenerated",
            baseClassName = "AbstractCjCDocLexerTest",
        )
    }

    private fun generateSuite(
        projectRoot: File,
        relativeTestDataRoot: String,
        generatedClassName: String,
        baseClassName: String,
    ) {
        val testDataRoot = projectRoot.resolve(relativeTestDataRoot)
        require(testDataRoot.isDirectory) { "testData root not found: ${testDataRoot.path}" }

        val outputFile = projectRoot.resolve(
            "psi/tests-gen/org/cangnova/cangjie/psi/test/$generatedClassName.kt",
        )
        outputFile.parentFile.mkdirs()
        outputFile.writeText(
            renderSuite(testDataRoot, projectRoot, generatedClassName, baseClassName),
            Charsets.UTF_8,
        )
        println("Generated: ${outputFile.path}")
    }

    /**
     * tests-gen 下只存放本生成器的输出；每轮先清理，避免切换套件后残留过期源码。
     */
    private fun cleanGeneratedTests(projectRoot: File) {
        val generatedRoot = projectRoot.resolve("psi/tests-gen/org/cangnova/cangjie/psi/test")
        if (generatedRoot.exists()) {
            generatedRoot.deleteRecursively()
        }
    }

    private fun renderSuite(
        testDataRoot: File,
        projectRoot: File,
        generatedClassName: String,
        baseClassName: String,
    ): String {
        val rootRel = projectRoot.toPath().relativize(testDataRoot.toPath()).toString().replace('\\', '/')
        val sb = StringBuilder()
        sb.appendLine("package org.cangnova.cangjie.psi.test")
        sb.appendLine()
        sb.appendLine("import com.intellij.testFramework.TestDataPath")
        sb.appendLine("import org.cangnova.cangjie.ObsoleteTestInfrastructure")
        sb.appendLine("import org.cangnova.cangjie.test.TestMetadata")
        sb.appendLine("import org.junit.jupiter.api.Nested")
        sb.appendLine("import org.junit.jupiter.api.Test")
        sb.appendLine()
        sb.appendLine("/** AUTO-GENERATED by TestGeneratorForPsi. DO NOT EDIT MANUALLY. */")
        sb.appendLine("@TestMetadata(\"$rootRel\")")
        sb.appendLine($$"@TestDataPath(\"${'$'}PROJECT_ROOT\")")
        sb.appendLine("@OptIn(ObsoleteTestInfrastructure::class)")
        sb.appendLine("@ObsoleteTestInfrastructure")
        sb.appendLine("class $generatedClassName : $baseClassName() {")
        sb.appendLine("    @Test")
        sb.appendLine("    fun testAllFilesPresent() {")
        sb.appendLine("        assertAllFilesPresentByMetadata(this, \"$rootRel\")")
        sb.appendLine("    }")

        val entries = testDataRoot.listFiles().orEmpty().sortedBy { it.name }
        for (entry in entries) {
            if (entry.isFile && entry.isTestDataFile()) {
                appendTestMethod(sb, entry, projectRoot, indent = "    ")
            }
        }
        for (entry in entries) {
            if (entry.isDirectory) {
                appendNestedClass(sb, entry, projectRoot, baseClassName, indent = "    ")
            }
        }

        sb.appendLine("}")
        return sb.toString()
    }

    /**
     * 渲染子目录对应的 @Nested 测试类；类级 @TestMetadata 使用相对仓库根的完整路径。
     */
    private fun appendNestedClass(
        sb: StringBuilder,
        dir: File,
        projectRoot: File,
        baseClassName: String,
        indent: String,
    ) {
        val entries = dir.listFiles().orEmpty().sortedBy { it.name }
        val files = entries.filter { it.isFile && it.isTestDataFile() }
        val subDirs = entries.filter { it.isDirectory }
        if (files.isEmpty() && subDirs.isEmpty()) return

        val dirRel = projectRoot.toPath().relativize(dir.toPath()).toString().replace('\\', '/')
        val className = toClassName(dir.name)

        sb.appendLine()
        sb.appendLine("$indent@TestMetadata(\"$dirRel\")")
        // 输出字面量 ${'$'}PROJECT_ROOT：生成文件中的 Kotlin 模板会求值为 $PROJECT_ROOT。
        sb.appendLine(indent + "@TestDataPath(\"\${'\$'}PROJECT_ROOT\")")
        sb.appendLine("$indent@Nested")
        sb.appendLine("${indent}inner class $className : $baseClassName() {")
        sb.appendLine("$indent    @Test")
        sb.appendLine("$indent    fun testAllFilesPresent() {")
        sb.appendLine("$indent        assertAllFilesPresentByMetadata(this, \"$dirRel\")")
        sb.appendLine("$indent    }")

        for (file in files) {
            appendTestMethod(sb, file, projectRoot, indent = "$indent    ")
        }
        for (subDir in subDirs) {
            appendNestedClass(sb, subDir, projectRoot, baseClassName, indent = "$indent    ")
        }

        sb.appendLine("$indent}")
    }

    private fun appendTestMethod(
        sb: StringBuilder,
        file: File,
        projectRoot: File,
        indent: String,
    ) {
        val testName = toTestMethodName(file.nameWithoutExtension)
        val rel = projectRoot.toPath().relativize(file.toPath()).toString().replace('\\', '/')
        // 方法级 @TestMetadata 只写文件名：类级 metadata 已给出目录，
        // assertAllFilesPresentByMetadata 按 类目录 + 文件名 解析覆盖关系。
        sb.appendLine()
        sb.appendLine("$indent@TestMetadata(\"${file.name}\")")
        sb.appendLine("$indent@Test")
        sb.appendLine("${indent}fun $testName() {")
        sb.appendLine("$indent    runTest(\"$rel\")")
        sb.appendLine("$indent}")
    }

    private fun toClassName(name: String): String = nameToKotlinIdentifier(nameToPascalCase(name))

    private fun toTestMethodName(base: String): String = "test" + nameToKotlinIdentifier(nameToPascalCase(base))

    /**
     * 测试数据文件：普通 `.cj`、`.cj.d` 声明文件或 `.cdoc` 文档注释；
     * golden sidecar（如 `.cj.tokens.txt`）不生成入口。
     */
    private fun File.isTestDataFile(): Boolean =
        isFile && (extension == "cj" || name.endsWith(".cj.d") || extension == "cdoc")

    private fun nameToPascalCase(name: String): String =
        name.split(Regex("[^A-Za-z0-9]+"))
            .filter { it.isNotBlank() }
            .joinToString("") { token -> token.replaceFirstChar { ch -> ch.uppercaseChar() } }
            .ifEmpty { "Generated" }

    /**
     * 目录 / 文件名可能以数字开头或含非法字符，生成的 Kotlin 标识符需要规整。
     */
    private fun nameToKotlinIdentifier(name: String): String {
        val result = StringBuilder()
        for (ch in name) {
            result.append(if (ch == '_' || ch.isLetterOrDigit()) ch else '_')
        }
        if (result.isEmpty()) {
            result.append("Generated")
        }
        if (result.first().isDigit()) {
            result.insert(0, '_')
        }
        return result.toString()
    }
}
